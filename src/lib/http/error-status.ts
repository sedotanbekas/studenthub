/** Kode yang dilempar dengan lebih dari satu status (ERROR_STATUS memuat yang paling sering). */
export const MIXED_STATUS_CODES: Readonly<Record<string, readonly number[]>> = Object.freeze({
  ACCOUNT_INACTIVE: [401, 403],
});

/** Status HTTP terdokumentasi untuk sebuah kode error; kode tak dikenal -> 422. */
export function statusForCode(code: string): number {
  return Object.hasOwn(ERROR_STATUS, code) ? (ERROR_STATUS[code] ?? DEFAULT_ERROR_STATUS) : DEFAULT_ERROR_STATUS;
}
